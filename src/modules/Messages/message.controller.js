import { Router } from 'express';
import * as v from './message.validation.js';
import * as s from './message.service.js';
import { listSchema } from '../User/user.validation.js';
import { validation } from '../../middlewares/validation.middleware.js';
import { authentication, authorization } from '../../middlewares/auth.meddleware.js';
import { messageLimiter } from '../../middlewares/rateLimtter.meddleware.js';
const router = Router();
router.post('/send-message/:receiverId', messageLimiter, authentication({ optional: true }), validation(v.sendMessageValidation), s.sendMessage);
router.get('/public/:receiverId', validation(v.publicListValidation), s.publicMessages);
router.get('/shared/:shareId/image', validation(v.shareValidation), s.shareImage);
router.get('/shared/:shareId', validation(v.shareValidation), s.getShared);
router.use(authentication());
router.get('/get-message', validation(v.listValidation), s.getMessage);
router.get('/get-message-admin{/:receiverId}', authorization({ accessRole: [0] }), validation(v.listValidation), s.getMessage);
router.get('/reports', authorization({ accessRole: [0] }), validation(v.reportListValidation), s.listReports);
router.patch('/reports/:reportId', authorization({ accessRole: [0] }), validation(v.resolveValidation), s.resolveReport);
router.get('/admin/stats', authorization({ accessRole: [0] }), s.adminStatistics);
router.get('/admin/audit', authorization({ accessRole: [0] }), validation(listSchema), s.auditLog);
router.patch('/:messageId', validation(v.updateValidation), s.updateMessage);
router.delete('/:messageId', validation(v.messageValidation), s.deleteMessage);
router.post('/:messageId/report', validation(v.reportValidation), s.reportMessage);
router.post('/:messageId/block', validation(v.messageValidation), s.blockSender);
export default router;

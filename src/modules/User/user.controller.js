import { Router } from 'express';
import * as s from './user.service.js';
import * as v from './user.validation.js';
import { authentication, authorization } from '../../middlewares/auth.meddleware.js';
import { validation } from '../../middlewares/validation.middleware.js';
import { localFileUpload, fileValidation } from '../../Utils/multer/local.multer.js';
import { magicNumberValidation } from '../../middlewares/magicNumber.middleware.js';
import { authLimiter, uploadLimiter } from '../../middlewares/rateLimtter.meddleware.js';
import { streamNotifications } from '../../Utils/notifications.js';
const router = Router();
router.use(authentication());
router.get('/', s.getprofile);
router.patch('/', validation(v.profileSchema), s.updateProfile);
router.get('/stats', s.statistics);
router.get('/export', authLimiter, s.exportData);
router.get('/notifications', streamNotifications);
router.get('/blocks', validation(v.listSchema), s.listBlocks);
router.delete('/blocks/:blockId', validation(v.blockSchema), s.unblock);
router.delete('/me', authLimiter, validation(v.deleteSelfSchema), s.deleteSelf);
router.patch(['/update-profile-pic', '/upadate-profile-pic'], uploadLimiter, localFileUpload().single('attachments'), validation(v.updateProfilePicSchema), magicNumberValidation(fileValidation.images), s.updateProfilePic);
router.patch(['/update-cover-pic', '/upadate-cover-pic'], uploadLimiter, localFileUpload().array('attachments', 5), validation(v.coverImagesValidation), magicNumberValidation(fileValidation.images), s.updateCoverPic);
router.patch('/update-password', authLimiter, validation(v.updatePasswordSchema), s.updatePassword);
router.delete('{/:userId}/freeze-account', validation(v.freezeAccountSchema), s.freezeAccount);
router.patch('/:userId/restore-account', authorization({ accessRole: [0] }), validation(v.restoreAccountSchema), s.restoreAccount);
router.delete('/:userId/hard-delete', authorization({ accessRole: [0] }), validation(v.hardDeleteAccountSchema), s.hardDeleteAccount);
export default router;

import { Router } from 'express';
import * as s from './auth.service.js';
import * as v from './auth.validation.js';
import { validation } from '../../middlewares/validation.middleware.js';
import { authentication } from '../../middlewares/auth.meddleware.js';
import { authLimiter, emailLimiter } from '../../middlewares/rateLimtter.meddleware.js';
const router = Router();
router.post('/signup', emailLimiter, validation(v.signupSchema), s.signup);
router.patch('/confirm-email', authLimiter, validation(v.confirmEmailSchema), s.confirmEmail);
router.post('/resend-confirmation', emailLimiter, validation(v.forgetPasswordSchema), s.resendConfirmation);
router.post('/login', authLimiter, validation(v.loginSchema), s.login);
router.post('/social-login', authLimiter, validation(v.googleSchema), s.loginWithGoogle);
router.post('/refresh-token', authLimiter, authentication({ tokenType: 1 }), s.refreshToken);
router.post(['/logout', '/logout-with-redis'], authentication(), validation(v.logoutSchema), s.logout);
router.patch('/forget-password', emailLimiter, validation(v.forgetPasswordSchema), s.forgetPassword);
router.patch('/reset-password', authLimiter, validation(v.resetPasswordSchema), s.resetPassword);
router.get('/sessions', authentication(), s.listSessions);
router.delete('/sessions/:sessionId', authentication(), validation(v.sessionSchema), s.revokeSession);
export default router;
